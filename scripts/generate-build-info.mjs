import fs from 'node:fs';
import path from 'node:path';

const rootDirectory = process.cwd();

const sequenceFilePath = path.join(
  rootDirectory,
  '.build-sequence.json'
);

const outputFilePath = path.join(
  rootDirectory,
  'src',
  'app',
  'core',
  'config',
  'build-info.generated.ts'
);

function pad(value) {
  return String(value).padStart(2, '0');
}

function getLocalBuildDate() {
  const now = new Date();

  return [
    now.getFullYear(),
    pad(now.getMonth() + 1),
    pad(now.getDate())
  ].join('.');
}

function readSequenceFile() {
  if (!fs.existsSync(sequenceFilePath)) {
    return {};
  }

  try {
    return JSON.parse(
      fs.readFileSync(sequenceFilePath, 'utf8')
    );
  } catch {
    return {};
  }
}

function writeSequenceFile(sequenceData) {
  fs.writeFileSync(
    sequenceFilePath,
    `${JSON.stringify(sequenceData, null, 2)}\n`,
    'utf8'
  );
}

function generateBuildInfo() {
  const buildDate = getLocalBuildDate();
  const sequenceData = readSequenceFile();

  const previousSequence = Number(
    sequenceData[buildDate] ?? 0
  );

  const nextSequence = previousSequence + 1;
  const build = `${buildDate}.${nextSequence}`;

  sequenceData[buildDate] = nextSequence;

  fs.mkdirSync(path.dirname(outputFilePath), {
    recursive: true
  });

  const generatedContent = `/*
 * AUTO-GENERATED FILE.
 * Do not edit this file manually.
 * Generated by scripts/generate-build-info.mjs
 */

export const BUILD_INFO = {
  build: '${build}',
  generatedAt: '${new Date().toISOString()}'
} as const;
`;

  fs.writeFileSync(
    outputFilePath,
    generatedContent,
    'utf8'
  );

  writeSequenceFile(sequenceData);

  console.log(`Build information generated: ${build}`);
}

generateBuildInfo();